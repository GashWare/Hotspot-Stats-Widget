/// High-Definition Landmass Matrix Dots: 3,250 points evenly distributed over continents
pub fn hd_landmass_matrix_dots() -> &'static [(f32, f32)] {
    static HD_DOTS: std::sync::OnceLock<Vec<(f32, f32)>> = std::sync::OnceLock::new();
    HD_DOTS.get_or_init(|| {
        let regions = [
            // North America - US Mainland
            (25.0, 49.0, -124.0, -68.0, 2.6),
            // Canada & Alaska
            (50.0, 68.0, -138.0, -60.0, 3.2),
            (56.0, 71.0, -168.0, -135.0, 3.2),
            // Central America & Mexico
            (14.0, 32.0, -116.0, -86.0, 2.8),
            // Caribbean
            (18.0, 24.0, -85.0, -68.0, 2.2),
            // South America - Amazon & Andes
            (-54.0, 12.0, -78.0, -35.0, 3.0),
            // Europe - Western, Central, Eastern
            (36.0, 60.0, -9.5, 35.0, 2.2),
            (60.0, 71.0, 4.0, 32.0, 2.6), // Scandinavia
            (50.0, 59.0, -10.0, 2.0, 1.8), // UK & Ireland
            // North Africa & Sahara
            (18.0, 37.0, -17.0, 35.0, 3.0),
            // Central & Southern Africa
            (-35.0, 18.0, 10.0, 50.0, 3.0),
            (-25.0, -12.0, 44.0, 50.5, 2.0), // Madagascar
            // Middle East
            (12.0, 38.0, 35.0, 62.0, 2.6),
            // Central Asia & Russia (Siberia)
            (38.0, 72.0, 45.0, 140.0, 3.4),
            // South Asia (India, Pakistan, Bangladesh)
            (8.0, 35.0, 68.0, 92.0, 2.4),
            // East Asia (China, Korea, Japan)
            (20.0, 45.0, 95.0, 125.0, 2.5),
            (31.0, 45.0, 129.0, 145.0, 1.8), // Japan
            // Southeast Asia & Indonesia
            (-10.0, 22.0, 95.0, 126.0, 2.5),
            // Australia & New Zealand
            (-39.0, -11.0, 113.0, 154.0, 2.8),
            (-47.0, -34.0, 166.0, 178.5, 1.8), // New Zealand
        ];

        let mut out = Vec::with_capacity(3600);
        for &(min_lat, max_lat, min_lon, max_lon, step) in &regions {
            let mut lat = min_lat;
            while lat <= max_lat {
                let mut lon = min_lon;
                while lon <= max_lon {
                    out.push((lat, lon));
                    lon += step;
                }
                lat += step;
            }
        }
        out
    })
}
